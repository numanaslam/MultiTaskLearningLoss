%% Move files
movedCount = 0;
skippedCount = 0;
errorCount = 0;
errors = {};

for i = 1:length(fileMappings)
    sourceFile = fileMappings{i}{1};
    targetFolder = fileMappings{i}{2};
    
    if ~exist(sourceFile, 'file')
        skippedCount = skippedCount + 1;
        if ~dryRun
            fprintf('  Skipped (not found): %s\n', sourceFile);
        end
        continue;
    end
    
    % Check if target folder exists
    if ~exist(targetFolder, 'dir')
        if ~dryRun
            mkdir(targetFolder);
            fprintf('  Created folder: %s\n', targetFolder);
        end
    end
    
    targetPath = fullfile(targetFolder, sourceFile);
    
    % Check if target already exists
    if exist(targetPath, 'file')
        if ~dryRun
            warning('Target already exists: %s', targetPath);
            response = input(sprintf('Overwrite %s? (y/n): ', sourceFile), 's');
            if ~strcmpi(response, 'y')
                fprintf('  Skipped: %s\n', sourceFile);
                skippedCount = skippedCount + 1;
                continue;
            end
        else
            fprintf('  Would skip (exists): %s -> %s\n', sourceFile, targetPath);
            skippedCount = skippedCount + 1;
            continue;
        end
    end
    
    if dryRun
        fprintf('  Would move: %s -> %s\n', sourceFile, targetPath);
        movedCount = movedCount + 1;
    else
        try
            [status, msg] = movefile(sourceFile, targetPath);
            if status
                fprintf('  Moved: %s -> %s\n', sourceFile, targetPath);
                movedCount = movedCount + 1;
            else
                error('Failed to move: %s\nError: %s', sourceFile, msg);
                errorCount = errorCount + 1;
                errors{end+1} = sprintf('%s: %s', sourceFile, msg);
            end
        catch ME
            errorCount = errorCount + 1;
            errors{end+1} = sprintf('%s: %s', sourceFile, ME.message);
            fprintf('  ERROR moving %s: %s\n', sourceFile, ME.message);
        end
    end
end

%% Summary
fprintf('\n=== MIGRATION SUMMARY ===\n');
