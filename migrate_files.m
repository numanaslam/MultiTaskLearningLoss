    fprintf('DRY RUN - No files were actually moved\n');
    fprintf('To actually move files, run: migrate_files(false)\n\n');
end
fprintf('Files processed: %d\n', length(fileMappings));
fprintf('Moved: %d\n', movedCount);
fprintf('Skipped: %d\n', skippedCount);
if errorCount > 0
    fprintf('Errors: %d\n', errorCount);
    fprintf('\nErrors:\n');
    for i = 1:length(errors)
        fprintf('  %s\n', errors{i});
    end
end

